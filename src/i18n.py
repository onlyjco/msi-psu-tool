_TABLE = EN if os.environ.get("MSI_PSU_LANG", "zh").lower().startswith("en") else ZH


def t(key: str, default: str | None = None) -> str:
    """Look up a string; unknown keys fall back to the key itself."""
    return _TABLE.get(key, default if default is not None else key)


def alert(name: str) -> str:
    """Translate an alert enum name, keeping the raw name if unknown."""
    return _TABLE.get(f"alert_{name}", name)
